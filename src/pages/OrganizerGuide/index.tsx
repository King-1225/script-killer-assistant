  const [clueDistForm] = Form.useForm();
  const [faqForm] = Form.useForm();
  const [endingForm] = Form.useForm();
  
  // 模态框状态
  const [truthModalVisible, setTruthModalVisible] = useState(false);
  const [stepModalVisible, setStepModalVisible] = useState(false);
  const [clueDistModalVisible, setClueDistModalVisible] = useState(false);
  const [faqModalVisible, setFaqModalVisible] = useState(false);
  const [endingModalVisible, setEndingModalVisible] = useState(false);
  const [previewModalVisible, setPreviewModalVisible] = useState(false);
