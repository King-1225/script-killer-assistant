  const loadProjectData = async (projectId: string) => {
    try {
      setIsLoading(true);
      
      // 获取项目数据
      const project = storageService.getProject(projectId);
      if (project) {
        // 获取角色数据
        setCharacters(project.characters || []);
        
        // 获取线索数据
        const allClues: Clue[] = [];
        if (project.scenes && Array.isArray(project.scenes)) {
          project.scenes.forEach(scene => {
            if (scene.clues && Array.isArray(scene.clues)) {
              allClues.push(...scene.clues);
            }
          });
        }
        setClues(allClues);
        
        // 获取组织者手册数据
        const savedGuide = project.organizerGuide || {
          truthChapters: [],
          hostingSteps: [],
          clueDistributions: [],
          faqs: [],
          endings: [],
          autoGenerated: false
        };
        setGuide(savedGuide);
        
        // 自动生成线索发放设置
      if (allClues.length > 0 && (!savedGuide.clueDistributions || savedGuide.clueDistributions.length === 0)) {
        generateClueDistributions(allClues);
      }
      }
      
      setCurrentProjectId(projectId);
    } catch (error) {
      console.error('加载项目数据失败:', error);
      message.error('加载项目数据失败');
    } finally {
      setIsLoading(false);
    }
  };

  // 初始化数据加载
  const loadData = async () => {
    setIsLoading(true);
    try {
      let projectId = storageService.getCurrentProjectId();
      if (!projectId) {
        const projects = storageService.getProjects();
        if (projects && projects.length > 0) {
          projectId = projects[0].id;
          storageService.setCurrentProjectId(projectId);
        }
      }
      
      if (projectId) {
        setCurrentProjectId(projectId);
        await loadProjectData(projectId);
      }
    } catch (error) {
      message.error('加载数据失败');
      console.error('加载数据失败:', error);
    } finally {
      setIsLoading(false);
    }
  };

  // 自动生成线索发放设置
  const generateClueDistributions = (allClues: Clue[]) => {
    const distributions: ClueDistribution[] = allClues.map(clue => ({
      clueId: clue.id,
      clueName: clue.name,
      phase: '第一幕',
      method: '公开',
      condition: '自动发放',
      notes: ''
    }));
    
    const updatedGuide = { ...guide, clueDistributions: distributions };
    setGuide(updatedGuide);
    if (currentProjectId) {
      storageService.updateProject(currentProjectId, { organizerGuide: updatedGuide });
    }
  };

  // 保存组织者手册
  const saveGuide = () => {
    if (currentProjectId) {
      storageService.updateProject(currentProjectId, { organizerGuide: guide });
      message.success('保存成功');
    }
  };

